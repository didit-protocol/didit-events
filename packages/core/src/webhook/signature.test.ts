import { createHmac } from "node:crypto";
import { describe, expect, it } from "vitest";
import fixture from "../didit/fixtures/webhook.json";
import vectors from "../didit/fixtures/signature-vectors.json";
import { canonicalizeV2, signV2, verifyWebhookSignature } from "./signature.ts";
const headers = () => new Headers({ "x-signature-v2": fixture.signatureV2, "x-timestamp": String(fixture.payload.timestamp) });
const now = new Date(fixture.payload.timestamp * 1000);
describe("Didit Python V2 reference fixtures", () => {
  it("matches sorted keys, Unicode, integral float shortening, exponents and large integers", () => {
    expect(canonicalizeV2(fixture.raw)).toBe(fixture.canonical);
    expect(signV2(fixture.raw, fixture.secret)).toBe(fixture.signatureV2);
    expect(verifyWebhookSignature(fixture.raw, headers(), fixture.secret, now)).toBe(true);
    expect(canonicalizeV2('{"z":90.0,"tiny":1.2e-5,"big":1e21,"negative":-0.0,"2":2,"10":10}')).toBe('{"10":10,"2":2,"big":1000000000000000000000,"negative":0,"tiny":1.2e-05,"z":90}');
    expect(canonicalizeV2('{"😀":1,"\uE000":2}')).toBe('{"":2,"😀":1}');
  });
  it("matches 128 seeded IEEE-754 vectors generated by the copied Python reference", () => {
    for (const vector of vectors) expect(canonicalizeV2(vector.raw)).toBe(vector.canonical);
  });
  it("key order and ASCII escaping do not change V2", () => {
    expect(signV2('{"name":"Jos\\u00e9","a":90.0}', "secret")).toBe(signV2('{"a":90,"name":"José"}', "secret"));
  });
  it.each([[-301, false], [-300, true], [300, true], [301, false]])("timestamp delta %ss", (delta, valid) => {
    expect(verifyWebhookSignature(fixture.raw, headers(), fixture.secret, new Date(now.getTime() + delta * 1000))).toBe(valid);
  });
  it("rejects tamper, forged fresh timestamp, missing timestamp and signature downgrade", () => {
    expect(verifyWebhookSignature(fixture.raw, headers(), fixture.secret, new Date(Number.NaN))).toBe(false);
    expect(verifyWebhookSignature(fixture.raw.replace("Approved", "Declined"), headers(), fixture.secret, now)).toBe(false);
    const fresh = headers(); fresh.set("x-timestamp", String(fixture.payload.timestamp + 1000));
    expect(verifyWebhookSignature(fixture.raw, fresh, fixture.secret, new Date(now.getTime() + 1000_000))).toBe(false);
    const missing = headers(); missing.delete("x-timestamp"); expect(verifyWebhookSignature(fixture.raw, missing, fixture.secret, now)).toBe(false);
    const downgrade = headers(); downgrade.set("x-signature-v2", "bad"); downgrade.set("x-signature", fixture.signature);
    expect(verifyWebhookSignature(fixture.raw, downgrade, fixture.secret, now)).toBe(false);
  });
  it("raw fallback verifies original bytes only and rejects duplicate keys", () => {
    expect(verifyWebhookSignature(fixture.raw, new Headers({ "x-signature": fixture.signature, "x-timestamp": String(fixture.payload.timestamp) }), fixture.secret, now)).toBe(true);
    const raw = `{"timestamp":${fixture.payload.timestamp},"timestamp":${fixture.payload.timestamp}}`;
    const signature = createHmac("sha256", fixture.secret).update(raw).digest("hex");
    expect(verifyWebhookSignature(raw, new Headers({ "x-signature": signature, "x-timestamp": String(fixture.payload.timestamp) }), fixture.secret, now)).toBe(false);
  });
  it.each(['{"x":NaN}', '{"x":1e999}', '{"x":1,"x":2}', '{"x":"\\ud800"}', '[1,]', '{} garbage', '{"x":\u00a01}', '{"x":\f1}'])("rejects malformed or non-canonical JSON %s", raw => { expect(() => canonicalizeV2(raw)).toThrow(); });
});
